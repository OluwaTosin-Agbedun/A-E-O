function lead(name: string, votes: number) {
  const info = PARTY_INFO[name] || { fullName: name, color: 'bg-slate-600' };
  return {
    name,
    fullName: info.fullName,
    color: info.color,
    votes
  };
}

function oth(votes: number) {
  return {
    name: 'Others',
    fullName: 'Other Parties',
    color: 'bg-slate-400',
    votes
  };
}

function lga(
  lgaName: string,
  accreditedVoters: number,
  validVotes: number,
  rejectedVotes: number,
  totalVotes: number,
  p1: string, v1: number,
  p2: string, v2: number,
  p3: string, v3: number,
  othersVotes: number
): LgaPartyStanding {
  return {
    lgaName,
    accreditedVoters,
    validVotes,
    rejectedVotes,
    totalVotes,
    first: lead(p1, v1),
    second: lead(p2, v2),
    third: lead(p3, v3),
    others: oth(othersVotes)
  };
}

